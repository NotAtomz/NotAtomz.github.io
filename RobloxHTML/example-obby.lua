-- Original parent: Workspace.Seat
spawn(function()

    local seat = part9
    
    local startPosition = seat.Position
    local endPosition = startPosition + Vector3.new(-54, 0, 0)
    
    local steps = 200
    local waitTime = 0.03
    
    local moving = false
    
    local function moveSeat(fromPosition, toPosition)
    	moving = true
    
    	for i = 0, steps do
    		local alpha = i / steps
    
    		seat.Position = Vector3.new(
    			fromPosition.X + (toPosition.X - fromPosition.X) * alpha,
    			fromPosition.Y + (toPosition.Y - fromPosition.Y) * alpha,
    			fromPosition.Z + (toPosition.Z - fromPosition.Z) * alpha
    		)
    
    		wait(waitTime)
    	end
    
    	seat.Position = toPosition
    	moving = false
    end
    
    seat:GetPropertyChangedSignal("Occupant"):Connect(function()
    	if moving then
    		return
    	end
    
    	if seat.Occupant then
    		moveSeat(
    			seat.Position,
    			endPosition
    		)
    	else
    		moveSeat(
    			seat.Position,
    			startPosition
    		)
    	end
    end)

end)

